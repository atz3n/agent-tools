#!/bin/bash

# Builds a docker image

###################################################################################################
# CONFIGURATION
###################################################################################################

IMAGE_NAME="gh-proxy"


###################################################################################################
# DEFINES
###################################################################################################

HERE="$(pwd)/$(dirname $0)"
DOCKER_FILE="${HERE}/../docker/Dockerfile"
CONEXT_PATH="${HERE}/.."


###################################################################################################
# MAIN
###################################################################################################

echo "[INFO] Building image ${IMAGE_NAME}..."
docker build -f ${DOCKER_FILE} ${CONEXT_PATH} -t ${IMAGE_NAME}
echo "[INFO] Done."
