#!/bin/bash

# Builds the odoo-proxy Docker image

###################################################################################################
# CONFIGURATION
###################################################################################################

IMAGE_NAME="odoo-proxy"


###################################################################################################
# DEFINES
###################################################################################################

HERE="$(pwd)/$(dirname $0)"
DOCKER_FILE="${HERE}/../docker/Dockerfile"
CONTEXT_PATH="${HERE}/.."


###################################################################################################
# MAIN
###################################################################################################

echo "[INFO] Building image ${IMAGE_NAME}..."
docker build -f ${DOCKER_FILE} ${CONTEXT_PATH} -t ${IMAGE_NAME}
echo "[INFO] Done."
