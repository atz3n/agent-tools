#!/bin/bash

# Pauses the odoo-proxy container (stops but keeps state)

###################################################################################################
# CONFIGURATION
###################################################################################################

PROJECT_NAME="odoo-proxy"


###################################################################################################
# DEFINES
###################################################################################################

HERE="$(pwd)/$(dirname $0)"


###################################################################################################
# MAIN
###################################################################################################

cd ${HERE}

cd ../docker
docker compose -p ${PROJECT_NAME} pause
